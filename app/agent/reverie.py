"""Nightly reverie — the agent's own context-budget cleanup turn.

Added 2026-10-23 (per Mal):

  "I want to clean up the optional reverie.md and enable its use as a
   config setting in config.yaml (enabled, timing, file target percentage,
   permanent memory target percentage). The intent is unlike openclaws
   dreams.md, is instigates a serious nightly cleanup turn. For example,
   it should prompt the agent to run (using the last 50 turn history as
   normal), unpin/update stale permanent memory entries, and then try to
   get the identity files (excluding SOUL.md) and permanent memory token
   budgets down to say 60% or less so it's unlikely that the agent will
   hit the 85% warning the following day. Additionally it should do some
   reflection and planning, which can be emitted as proposals to the user
   (informally, just chat emission) at the end of it's reverie turn.
   Unlike heartbeat, the reverie turn will be captured in the turns table
   as normal (so the continuation next day will have context of the
   changed memories etc.). If no turns ran in a day, reverie should not
   fire (to avoid filling up turn history with no-op reveries)."

What this is NOT
----------------
It is not a heartbeat. A heartbeat is a system event: it is not a turn,
it does not enter the conversation, and it leaves no trace in the turns
table. The reverie IS a turn: it runs through the normal agent loop, so
it gets the agent's last 50 turns of history, it is persisted like any
other turn, and tomorrow's conversation continues with the context of
what tonight's reverie changed.

How it fires
------------
A systemd --user timer (harness-reverie.timer, generated by
scripts/install_reverie_timer.sh from the config's `reverie.at`) POSTs
to /api/v1/internal/reverie, which calls into this module.

Guard rails
-----------
* It only fires when the agent had REAL activity in the window
  (config.reverie.activity_window_hours). Reverie turns are marked in
  the turn's trajectory, so they do not count as activity themselves —
  otherwise the turn history would fill with no-op reveries.
* The protected identity files (SOUL.md by default) are never edited by
  the reverie: they hold the super important rules and may only change
  with the user's explicit permission. The brief says so, and the
  exec_bash tool refuses to touch them during a reverie turn.
"""
from __future__ import annotations

import logging
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

log = logging.getLogger(__name__)

# The trajectory marker written on the user turn of a reverie turn. The
# activity check uses it to tell a reverie turn apart from a real one.
REVERIE_TRAJECTORY_KIND = "reverie"

# Agent names end up in SQL (the <agent>.turns table name), so they are
# validated against this pattern before they are interpolated. The
# installed roster is a config value, but the name still travels
# through the DB, so it is checked here too.
_AGENT_NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,39}$")

# The first characters of a reverie brief. The HMI uses it to render the
# turn as a reverie block instead of a giant "user said this" bubble.
REVERIE_PREFIX = "<reverie"


def reverie_trajectory(agent_name: str, started_at: datetime) -> dict:
    """The trajectory marker stored on a reverie's user turn."""
    return {
        "kind": REVERIE_TRAJECTORY_KIND,
        "agent": agent_name,
        "started_at": started_at.isoformat(),
    }


def activity_count(pool: Any, agent_name: str, hours: int) -> int:
    """How many REAL (non-reverie) user turns the agent had recently.

    "Real" means a human (or a group message) actually said something.
    Reverie turns carry a trajectory marker and are excluded, so a
    nightly reverie never makes the next night look busy.
    """
    sql = f"""
        SELECT count(*)
          FROM {agent_name}.turns
         WHERE created_at > now() - make_interval(hours => %s)
           AND role = 'user'
           AND (trajectory IS NULL
                OR trajectory->>'kind' IS DISTINCT FROM %s)
    """
    if not _AGENT_NAME_RE.match(agent_name or ""):
        raise ValueError(f"invalid agent name: {agent_name!r}")
    with pool.connection() as conn:
        with conn.cursor() as cur:
            cur.execute(sql, (int(hours), REVERIE_TRAJECTORY_KIND))
            row = cur.fetchone()
    return int(row[0]) if row else 0


def _fmt_bytes(n: int) -> str:
    return f"{n:,}"


# The reverie mode block. It goes in the SYSTEM prompt, not in the user
# message: a user-role instruction was READ and IGNORED by the agent
# (an agent picked up an unfinished Google Docs task from the conversation
# history instead of doing the cleanup). The scope rule has to outrank
# the pull of that history, so it lives where the agent's role is
# defined.
REVERIE_MODE = """<reverie_mode>
This turn is a MAINTENANCE turn. The user message is your reverie brief.

Your ONLY job tonight is what the brief says:
  1. clean up your permanent memory (unpin / update / delete what is
     stale, move the detail into files, leave pointers),
  2. clean up the identity files down to the target percentages,
  3. finish with reflection + 2-4 proposals for the user.

Do NOT continue, finish, or "helpfully pick up" any task that appears in
the conversation history — not even an unfinished one, not even one you
were mid-way through. The history is EVIDENCE for the cleanup, not a work
queue. If you see open work there, name it in your proposals and leave it
for the user to ask for.

When the cleanup and the report are done: STOP. Do not start anything
new.
</reverie_mode>"""


def build_brief(
    agent_name: str,
    cfg: Any,
    bootstrap: Any,
    memory: Any,
    *,
    now: datetime | None = None,
) -> str:
    """Build the reverie prompt for one agent.

    The brief carries the NUMBERS the agent needs (current usage vs cap
    vs target) so it can actually do the cleanup, plus the rules
    (protected files, move-detail-out, end with proposals for the user).
    """
    now = now or datetime.now(timezone.utc).astimezone()
    rv = cfg.reverie
    file_target = float(rv.file_target_pct)
    mem_target = float(rv.memory_target_pct)
    protected = {f.strip().lower() for f in (rv.protected_files or ())}

    identity_dir = ""
    try:
        identity_dir = str(bootstrap.workspace_root)
    except Exception:
        pass

    lines: list[str] = []
    lines.append(
        f"{REVERIE_PREFIX} agent=\"{agent_name}\" at=\"{now.isoformat()}\">"
    )
    lines.append("")
    lines.append(
        "This is your nightly reverie: a real working session on your own "
        "context, not a status ping. The last 50 turns of this "
        "conversation are in your context as usual - read them, they are "
        "the evidence you need."
    )
    lines.append("")
    lines.append(
        "SCOPE - this matters. Tonight's job is ONLY the three things "
        "below: (1) clean up your permanent memory, (2) clean up the "
        "identity files, (3) reflect and put proposals in your report. "
        "Do NOT pick up or continue any task that appears in the "
        "history, even an unfinished one, even one you were mid-way "
        "through. If the history shows work that is still open, name it "
        "in the proposals and leave it for the user to ask for. The "
        "history is EVIDENCE for the cleanup, not a work queue."
    )
    lines.append("")

    # --- the numbers -------------------------------------------------
    lines.append("CONTEXT BUDGET - current usage, target, and what to cut:")
    lines.append("")
    try:
        usage = bootstrap.file_usage()
    except Exception as exc:
        log.warning("reverie: file_usage failed for agent=%s: %s", agent_name, exc)
        usage = []
    for u in usage:
        name = u.get("name", "?")
        size = int(u.get("bytes") or 0)
        cap = int(u.get("cap") or 0)
        pct = float(u.get("pct") or 0.0)
        if name.lower() in protected:
            lines.append(
                f"  {name:<14} {_fmt_bytes(size):>9} / {_fmt_bytes(cap):>9} bytes "
                f"({pct * 100:5.1f}%)  PROTECTED - do not edit (user permission only)"
            )
            continue
        if not cap:
            continue
        target_bytes = int(cap * file_target)
        if size > target_bytes:
            lines.append(
                f"  {name:<14} {_fmt_bytes(size):>9} / {_fmt_bytes(cap):>9} bytes "
                f"({pct * 100:5.1f}%)  OVER TARGET (<= {file_target * 100:.0f}% = "
                f"{_fmt_bytes(target_bytes)} bytes) - cut ~{_fmt_bytes(size - target_bytes)} bytes"
            )
        else:
            lines.append(
                f"  {name:<14} {_fmt_bytes(size):>9} / {_fmt_bytes(cap):>9} bytes "
                f"({pct * 100:5.1f}%)  ok (target <= {file_target * 100:.0f}%)"
            )

    # permanent memory
    try:
        pm = memory.permanent_usage()
    except Exception as exc:
        log.warning("reverie: permanent_usage failed for agent=%s: %s", agent_name, exc)
        pm = {"used_tokens": 0, "total_tokens": 0, "count": 0, "cap": 0, "dropped": 0}
    pm_cap = int(pm.get("cap") or 0)
    pm_total = int(pm.get("total_tokens") or 0)
    pm_used = int(pm.get("used_tokens") or 0)
    pm_count = int(pm.get("count") or 0)
    dropped = int(pm.get("dropped") or 0)
    if pm_cap:
        target_tokens = int(pm_cap * mem_target)
        pm_pct = 100.0 * pm_total / pm_cap
        if pm_total > target_tokens:
            lines.append(
                f"  {'permanent mem':<14} {_fmt_bytes(pm_total):>9} / "
                f"{_fmt_bytes(pm_cap):>9} tokens ({pm_pct:5.1f}%)  OVER TARGET "
                f"(<= {mem_target * 100:.0f}% = {_fmt_bytes(target_tokens)} tokens) - "
                f"cut ~{_fmt_bytes(pm_total - target_tokens)} tokens"
            )
        else:
            lines.append(
                f"  {'permanent mem':<14} {_fmt_bytes(pm_total):>9} / "
                f"{_fmt_bytes(pm_cap):>9} tokens ({pm_pct:5.1f}%)  ok "
                f"(target <= {mem_target * 100:.0f}%)"
            )
        lines.append(
            f"     {pm_count} permanent entr{'y' if pm_count == 1 else 'ies'}; "
            f"{dropped} of them are being DROPPED from your prompt right now "
            f"(the cap is {pm_cap:,} tokens, {_fmt_bytes(pm_used)} fit)."
        )
    lines.append("")

    # --- the job -----------------------------------------------------
    lines.append("THE JOB - do the work, do not describe the work:")
    lines.append("")
    lines.append(
        "1. PERMANENT MEMORY. Call memory_recent (and memory_recall when you "
        "need to search) to see the long-form memories, and check which are "
        "pinned. For each pinned entry decide: still true and still needed? "
        "keep it, and shorten it with memory_update if it is wordy. Stale, "
        "superseded, duplicated, or far too detailed? unpin it with "
        "memory_unpin. Anything you unpin or shorten must stay findable: "
        f"move the detail into a file under pie/{agent_name}/skills/, "
        f"pie/{agent_name}/scripts/ or pie/{agent_name}/docs/ and leave a "
        "one-line pointer in the memory itself. Get the permanent block to "
        f"{int(pm_cap * mem_target):,} tokens or less."
    )
    lines.append("")
    lines.append(
        "2. IDENTITY FILES. For every file marked OVER TARGET above, edit it "
        "so it ends up at or below the target bytes. The same rule applies: "
        "the file becomes a short index (\"## Topic -> path\") and the detail "
        f"moves under pie/{agent_name}/skills/, pie/{agent_name}/scripts/ or "
        f"pie/{agent_name}/docs/. The identity files live in {identity_dir}. "
        "Keep them valid markdown and keep the rules that matter - you are "
        "tidying, not gutting."
    )
    lines.append("")
    lines.append(
        "3. SOUL.md IS PROTECTED. Do not edit it, not a byte, not a line. It "
        "holds only the super important rules and may only change with the "
        "user's explicit permission. If you think it needs a change, put it "
        "in your report as a proposal instead of making it."
    )
    lines.append("")
    lines.append(
        "4. REFLECTION AND PLANNING. Read the recent turns and think about "
        "what keeps recurring, what you got wrong, what is unfinished, and "
        "what should change about how you work. Then END your turn with a "
        "report for the user (plain chat - no files, no email, nothing "
        "external): what you changed with before/after numbers, what you "
        "unpinned or rewrote and why, anything you could NOT get under "
        "target and why, and 2-4 PROPOSALS - decisions or actions you want "
        "the user to take. Be honest and specific. If there was nothing to "
        "do, say so plainly."
    )
    lines.append("")
    lines.append(
        "5. FINISH. When the cleanup is done and the report is written, "
        "stop. Do not start anything new. A reverie that does not end is "
        "worse than a reverie that does less."
    )
    lines.append("")
    lines.append("</reverie>")
    return "\n".join(lines)


def optional_prompt_file(bootstrap: Any, file_name: str) -> str:
    """Read the optional per-agent reverie instructions, if present.

    The file lives next to the identity files (pie/<agent>/identity/
    REVERIE.md). It is NOT injected into every prompt - it is read once
    a night and appended to the reverie brief, so the agent can add its
    own standing instructions for the reverie.
    """
    if not file_name or not bootstrap:
        return ""
    try:
        root = Path(bootstrap.workspace_root)
    except Exception:
        return ""
    path = root / file_name
    try:
        if not path.exists() or not path.is_file():
            return ""
        return path.read_text(encoding="utf-8").strip()
    except (OSError, UnicodeDecodeError) as exc:
        log.warning("reverie: could not read %s: %s", path, exc)
        return ""


def build_brief_with_agent_file(
    agent_name: str,
    cfg: Any,
    bootstrap: Any,
    memory: Any,
    *,
    now: datetime | None = None,
) -> str:
    """The reverie brief + the agent's own optional REVERIE.md."""
    brief = build_brief(agent_name, cfg, bootstrap, memory, now=now)
    extra = optional_prompt_file(bootstrap, cfg.reverie.prompt_file)
    if not extra:
        return brief
    return (
        brief
        + "\n\n"
        + f"<reverie_agent_notes source=\"{cfg.reverie.prompt_file}\">\n"
        + extra
        + "\n</reverie_agent_notes>"
    )


def resolve_user_id(pool: Any, email: str) -> int | None:
    """Look up the user the reverie runs as (by email)."""
    if not email:
        return None
    with pool.connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT id FROM public.users WHERE email = %s AND is_active = TRUE",
                (email.lower(),),
            )
            row = cur.fetchone()
    return int(row[0]) if row else None


def resolve_reverie_user_id(pool: Any, email: str) -> int | None:
    """The user id the reverie turn runs as.

    Primary: the configured email (config.reverie.user_email). Fallback:
    the first active admin. It never returns None unless there is no
    admin at all -- a reverie turn with user_id=None would land in
    whatever anonymous conversation happened to be touched last, which
    is exactly the kind of accident the is_group work was about.
    """
    if email:
        uid = resolve_user_id(pool, email)
        if uid is not None:
            return uid
        log.warning(
            "reverie: configured user %r not found; falling back to the first admin",
            email,
        )
    with pool.connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT id FROM public.users "
                " WHERE role = 'admin' AND is_active = TRUE "
                " ORDER BY id LIMIT 1"
            )
            row = cur.fetchone()
    return int(row[0]) if row else None


def plan_reverie(
    *,
    pool: Any,
    cfg: Any,
    agent_name: str,
    force: bool = False,
) -> dict:
    """Decide whether the reverie should fire for this agent.

    Returns {"agent": ..., "should_run": bool, "reason": str,
             "activity": int}. The activity check is the "if no turns ran
    in a day, don't fire" rule.
    """
    if not cfg.reverie.enabled:
        return {"agent": agent_name, "should_run": False,
                "reason": "reverie disabled in config", "activity": 0}
    if not force:
        activity = activity_count(pool, agent_name, cfg.reverie.activity_window_hours)
        if activity <= 0:
            return {
                "agent": agent_name,
                "should_run": False,
                "reason": (
                    f"no activity in the last {cfg.reverie.activity_window_hours}h"
                ),
                "activity": 0,
            }
        return {"agent": agent_name, "should_run": True,
                "reason": f"{activity} real turn(s) in the window", "activity": activity}
    activity = activity_count(pool, agent_name, cfg.reverie.activity_window_hours)
    return {"agent": agent_name, "should_run": True,
            "reason": "forced", "activity": activity}
